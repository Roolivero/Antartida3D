/**
 * Bakes the height of the land under the flight path over Tierra del Fuego, from IBCSO v2
 * (the same source as the regional relief): `pnpm --filter @antartida/core flight-ground`.
 * The regional mesh has no elevation grid to query at run time, and the profile is tiny.
 * Needs IBCSO_v2_bed.tif in ~/.cache/antartida3d/ibcso (or IBCSO_DIR). See docs/datos-relieve.md.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fromFile } from 'geotiff';
import proj4 from 'proj4';
import { FLIGHT_GROUND_SIDE, FLIGHT_GROUND_STEP, flightAt } from '../src/flight-path.ts';
import { FUEGIA_DATA_LIMIT_LAT, inFuegia } from '../src/fuegia.ts';
import { unproject } from '../src/projection.ts';

const here = dirname(fileURLToPath(import.meta.url));

proj4.defs('EPSG:9354', '+proj=stere +lat_0=-90 +lat_ts=-65 +lon_0=0 +x_0=0 +y_0=0 +datum=WGS84 +units=m +no_defs');
const toIbcso = proj4('EPSG:4326', 'EPSG:9354');

const tifPath = join(process.env.IBCSO_DIR || join(process.env.HOME || '', '.cache/antartida3d/ibcso'), 'IBCSO_v2_bed.tif');
if (!existsSync(tifPath)) {
  console.error(`IBCSO file missing: ${tifPath}`);
  process.exit(1);
}
const img = await (await fromFile(tifPath)).getImage();
const [originX, originY] = img.getOrigin();
const [resX, resY] = img.getResolution();
const width = img.getWidth();
const height = img.getHeight();
const data = (await img.readRasters())[0] as Int16Array;

/** Land elevation in meters at a map-space point; 0 on the sea or outside the data. */
function elevation(x: number, y: number): number {
  const { lon, lat } = unproject(x, y);
  if (lat > FUEGIA_DATA_LIMIT_LAT) return 0;
  const [px, py] = toIbcso.forward([lon, lat]);
  const c = Math.floor((px - originX) / resX);
  const r = Math.floor((py - originY) / resY);
  return c < 0 || r < 0 || c >= width || r >= height ? 0 : Math.max(0, data[r * width + c]);
}

const profile: number[] = [];
for (let i = 0; ; i++) {
  const t = i * FLIGHT_GROUND_STEP;
  const center = flightAt(t);
  if (!inFuegia(center.x, center.y)) break;
  let top = 0;
  // Every point within half a step along the path and FLIGHT_GROUND_SIDE to each side.
  for (let a = -4; a <= 4; a++) {
    const u = Math.max(0, t + (a / 8) * FLIGHT_GROUND_STEP);
    const p = flightAt(u);
    const q = flightAt(u + 1e-4);
    const len = Math.hypot(q.x - p.x, q.y - p.y);
    const nx = -(q.y - p.y) / len;
    const ny = (q.x - p.x) / len;
    for (let s = -20; s <= 20; s++) {
      const side = (s / 20) * FLIGHT_GROUND_SIDE;
      top = Math.max(top, elevation(p.x + nx * side, p.y + ny * side));
    }
  }
  profile.push(Math.round(top));
}
// Drop the trailing open sea.
while (profile.length > 1 && profile[profile.length - 1] === 0) profile.pop();

writeFileSync(
  join(here, '../src/flight-ground.ts'),
  `// Generated by scripts/build-flight-ground.ts from IBCSO v2 (CC BY 4.0). Do not edit by hand.

/**
 * Highest land (meters) under and beside the flight path over Tierra del Fuego, one value every
 * FLIGHT_GROUND_STEP of the trip from Ushuaia. Past the end there is only sea until Antarctica.
 */
export const FLIGHT_GROUND_M: readonly number[] = [${profile.join(', ')}];
`,
);
console.log(`flight-ground.ts: ${profile.length} samples, highest ${Math.max(...profile)} m`);
console.log(profile.join(' '));
